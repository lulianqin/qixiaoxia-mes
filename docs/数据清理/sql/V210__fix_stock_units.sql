-- 物料：辅助单位=箱，换算率=每箱数量，装箱规格文本
UPDATE qxx_md_item i JOIN tmp_fin_spec t ON i.item_code = t.item_code
   SET i.unit2='BOX', i.unit2_name='箱', i.conversion_rate=t.packing,
       i.package_spec=CONCAT(CAST(t.packing AS UNSIGNED), '个/箱')
 WHERE i.factory_id=1 AND t.packing IS NOT NULL AND t.packing > 0;

-- 库存：辅助单位/换算率/辅助数量（箱数）/PO号/订单号
UPDATE qxx_wm_material_stock s JOIN tmp_fin_spec t ON s.item_code = t.item_code
   SET s.unit2='BOX', s.unit2_name='箱',
       s.conversion_rate=IFNULL(NULLIF(t.packing,0),1),
       s.quantity_onhand2=IFNULL(t.boxes,0),
       s.quantity_available2=IFNULL(t.boxes,0),
       s.po_no=NULLIF(t.po_no,''),
       s.source_order_code=NULLIF(t.order_no,'')
 WHERE s.factory_id=1 AND s.del_flag='0';

