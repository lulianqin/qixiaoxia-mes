SET @now = NOW();
SET @op = 'admin';

-- ---------- 1. 库存表新增 PO 号 / 系统订单号 ----------
DROP PROCEDURE IF EXISTS qxx_add_stock_doc_cols;
DELIMITER $$
CREATE PROCEDURE qxx_add_stock_doc_cols()
BEGIN
  IF NOT EXISTS (SELECT 1 FROM information_schema.columns WHERE table_schema = DATABASE()
                  AND table_name = 'qxx_wm_material_stock' AND column_name = 'po_no') THEN
    ALTER TABLE `qxx_wm_material_stock` ADD COLUMN `po_no` varchar(64) DEFAULT NULL COMMENT '客户PO号' AFTER `lot_number`;
  END IF;
  IF NOT EXISTS (SELECT 1 FROM information_schema.columns WHERE table_schema = DATABASE()
                  AND table_name = 'qxx_wm_material_stock' AND column_name = 'source_order_code') THEN
    ALTER TABLE `qxx_wm_material_stock` ADD COLUMN `source_order_code` varchar(64) DEFAULT NULL COMMENT '来源系统订单号' AFTER `po_no`;
  END IF;
END$$
DELIMITER ;
CALL qxx_add_stock_doc_cols();
DROP PROCEDURE IF EXISTS qxx_add_stock_doc_cols;

-- ---------- 2. 单位字段从 unit_id 改为单位编码 ----------
UPDATE qxx_md_item SET unit_of_measure='PCS'  WHERE factory_id=1 AND unit_of_measure='200';
UPDATE qxx_md_item SET unit_of_measure='KG'   WHERE factory_id=1 AND unit_of_measure='201';
UPDATE qxx_md_item SET unit_of_measure='PAIR' WHERE factory_id=1 AND unit_of_measure='204';

-- 库存行按物料回填主单位（V209 里成品被误写成 KG）
UPDATE qxx_wm_material_stock s
  JOIN qxx_md_item i ON s.item_id = i.item_id AND i.factory_id = 1
   SET s.unit_of_measure = i.unit_of_measure, s.unit_name = i.unit_name
 WHERE s.factory_id = 1 AND s.del_flag = '0';

