-- ============================================================
-- V203: 销售订单明细新增「MES 产品名称」
--
-- 背景：
--   ERP 采购单下发时，MES 按「外部编码→名称」映射命中物料后会直接用 MES 物料
--   名称覆盖行上的产品名称，采购单原名称（如「牛皮纸袋」）在 MES 里彻底丢失，
--   与工厂/采购对单时无法区分到底对应哪个 ERP 产品。
--   改为：product_name 保留 ERP/SRM 源名称，映射到的 MES 物料名称另存本列，
--   列表/详情两列并列展示；工单仍按 MES 物料名称生产。
--
-- 字符集：utf8mb4
-- 日期：2026-11-23
-- ============================================================

SET NAMES utf8mb4;

ALTER TABLE qxx_sal_order_line
    ADD COLUMN mes_product_name VARCHAR(255) DEFAULT NULL
        COMMENT 'MES 产品名称(外部单映射到的物料名称,与源ERP产品名称并列展示)' AFTER product_name;
